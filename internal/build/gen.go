// kindSuffix names the gopgext/fmgr helpers that pass each kind of value:
// Arg, ArgPtr, ArgArray, ... and Return, ReturnPtr, ReturnArray, ...
var kindSuffix = [...]string{
	Scalar:        "",
	Nullable:      "Ptr",
	Array:         "Array",
	NullableArray: "ArrayPtr",
	NullableElems: "ArrayNullable",
	SetOf:         "Set",
	NullableSetOf: "SetNullable",
}

var goTmpl = template.Must(template.New("go").Funcs(template.FuncMap{
	"suffix": func(k TypeKind) string { return kindSuffix[k] },
	// arg is the expression that reads parameter i.
	"arg":         argExpr,
	"result":      resultStmt,
	"field":       fieldStmt,
	"read":        readStmt,
	"triggerCall": triggerCall,
}).Parse(`// Code generated by gopgext. DO NOT EDIT.

package main

{{if or .UsesAgg .UsesTrigger}}import (
{{if .UsesAgg}}	_gopgext_agg "gopgext/agg"
{{end}}	_gopgext_fmgr "gopgext/fmgr"
{{if .UsesTrigger}}	_gopgext_trigger "gopgext/trigger"
{{end}})
{{else}}import _gopgext_fmgr "gopgext/fmgr"
{{end}}
// Package initialization and main run when the library is loaded (_PG_init).
//
//export gopgext_go_init
func _gopgext_go_init(c *_gopgext_fmgr.Call) {
	defer c.End(c.Begin(false))
	_gopgext_fmgr.Init(c)
}
{{range .Funcs}}
// {{.GoName}}: {{.Signature}}
//
//export gopgext_go_{{.GoName}}
func _gopgext_go_{{.GoName}}(_c *_gopgext_fmgr.Call) {
	defer _c.End(_c.Begin({{.ReadOnly}}))
{{- if .Trigger}}
	{{triggerCall .}}
{{- else}}
	{{if and .Result .HasError}}_r, _err := {{else if .Result}}_r := {{else if .HasError}}_err := {{end -}}
	{{.GoName}}({{range $i, $p := .Params}}{{if $i}}, {{end}}{{arg $i $p}}{{end}})
{{- if .HasError}}
	if _err != nil {
		_c.Fail(_err)
		return
	}
{{- end}}
{{- with .Result}}
	{{result .}}
{{- end}}
{{- end}}
}
{{end -}}
{{range .Structs}}{{if .Composite}}
// _gopgext_read_{{.GoName}} reads a {{.GoName}} composite argument.
func _gopgext_read_{{.GoName}}(_r *_gopgext_fmgr.RowArg) (_v {{.GoName}}) {
{{- range $i, $f := .Fields}}
	{{read $i $f}}
{{- end}}
	return
}
{{end}}
// _gopgext_row_{{.GoName}} sets the columns of a {{.GoName}} row.
func _gopgext_row_{{.GoName}}(_v {{.GoName}}, _row *_gopgext_fmgr.Row) {
{{- range $i, $f := .Fields}}
	{{field $i $f}}
{{- end}}
}
{{end -}}
`))

func isArray(k TypeKind) bool { return k == Array || k == NullableArray || k == NullableElems }

// of is the suffix of the fmgr functions for arrays of extension-defined
// types (whose element type comes from the function's signature).
func of(t Type) string {
	if t.Custom != nil && isArray(t.Kind) {
		return "Of"
	}
	return ""
}

// conv converts expr between a //gopgext:type (as the Go type) and its
// representation: toRep converts to the representation.
func conv(t Type, expr string, toRep bool) string {
	from, to := t.Custom.GoName, t.Go
	if !toRep {
		from, to = to, from
	}
	switch t.Kind {
	case Nullable:
		return fmt.Sprintf("(*%s)(%s)", to, expr)
	case Array:
		return fmt.Sprintf("_gopgext_fmgr.Conv(%s, func(x %s) %s { return %[3]s(x) })", expr, from, to)
	case NullableArray:
		return fmt.Sprintf("_gopgext_fmgr.ConvPtr(%s, func(x %s) %s { return %[3]s(x) })", expr, from, to)
	case NullableElems:
		return fmt.Sprintf("_gopgext_fmgr.Conv(%s, func(x *%s) *%s { return (*%[3]s)(x) })", expr, from, to)
	}
	return fmt.Sprintf("%s(%s)", to, expr)
}

// argExpr is the expression that reads parameter i.
func argExpr(i int, p Param) string {
	t := p.Type
	if t.Go == aggState {
		return fmt.Sprintf("_gopgext_agg.Arg(_c, %d)", i)
	}
	if poly := polymorphic[t.Go]; poly != "" {
		if t.Kind == Nullable {
			return fmt.Sprintf("_gopgext_fmgr.Arg%sPtr(_c, %d)", poly, i)
		}
		return fmt.Sprintf("_gopgext_fmgr.Arg%s(_c, %d, %q)", poly, i, p.SQLName)
	}
	if st := t.Struct; st != nil { // a composite type
		if t.Kind == Nullable {
			return fmt.Sprintf("_gopgext_fmgr.ArgRowPtr(_c, %d, %d, _gopgext_read_%s)", i, len(st.Fields), st.GoName)
		}
		return fmt.Sprintf("_gopgext_fmgr.ArgRow(_c, %d, %q, %d, _gopgext_read_%s)", i, p.SQLName, len(st.Fields), st.GoName)
	}
	var e string
	if fixedSize(t.Go) != "" { // a fixed-size type passed by reference
		if t.Kind == Nullable {
			e = fmt.Sprintf("_gopgext_fmgr.ArgFixedPtr[%s](_c, %d)", t.Go, i)
		} else {
			e = fmt.Sprintf("_gopgext_fmgr.ArgFixed[%s](_c, %d, %q)", t.Go, i, p.SQLName)
		}
	} else if t.Kind == Nullable { // nil for NULL, so no name for the error
		e = fmt.Sprintf("_gopgext_fmgr.ArgPtr[%s](_c, %d)", t.Go, i)
	} else {
		e = fmt.Sprintf("_gopgext_fmgr.Arg%s%s[%s](_c, %d, %q)", kindSuffix[t.Kind], of(t), t.Go, i, p.SQLName)
	}
	if t.Custom != nil { // the representation, as the Go type
		return conv(t, e, false)
	}
	return e
}

// resultStmt returns the statement that sets the result _r of type t.
func resultStmt(t Type) string {
	if t.Go == aggState {
		return "_gopgext_agg.Return(_c, _r)"
	}
	if t.Struct != nil {
		fn := map[TypeKind]string{Scalar: "ReturnRow", Nullable: "ReturnRowPtr", SetOf: "ReturnRows"}[t.Kind]
		return fmt.Sprintf("_gopgext_fmgr.%s(_c, _r, _gopgext_row_%s)", fn, t.Struct.GoName)
	}
	if t.Go == recordType {
		return fmt.Sprintf("_gopgext_fmgr.ReturnRecord%s(_c, _r)", map[TypeKind]string{Nullable: "Ptr", SetOf: "Set"}[t.Kind])
	}
	if poly := polymorphic[t.Go]; poly != "" {
		return fmt.Sprintf("_gopgext_fmgr.Return%s%s(_c, _r)", poly, map[TypeKind]string{Nullable: "Ptr", SetOf: "Set"}[t.Kind])
	}
	if t.Custom == nil {
		return fmt.Sprintf("_gopgext_fmgr.Return%s(_c, _r)", kindSuffix[t.Kind])
	}
	if fixedSize(t.Go) != "" {
		return fmt.Sprintf("_gopgext_fmgr.ReturnFixed%s[%s](_c, %s)", kindSuffix[t.Kind], t.Go, conv(t, "_r", true))
	}
	var r string
	if t.Kind == SetOf {
		r = fmt.Sprintf("func(yield func(%[1]s) bool) {\n\t\tfor v := range _r {\n\t\t\tif !yield(%[1]s(v)) {\n\t\t\t\treturn\n\t\t\t}\n\t\t}\n\t}", t.Go)
	} else {
		r = conv(t, "_r", true)
	}
	return fmt.Sprintf("_gopgext_fmgr.Return%s%s[%s](_c, %s)", kindSuffix[t.Kind], of(t), t.Go, r)
}

// triggerCall returns the body of a trigger function's wrapper.
func triggerCall(f *Function) string {
	var b strings.Builder
	if f.Trigger == "event_trigger" {
		b.WriteString("_t := _gopgext_trigger.EventArg(_c)\n")
	} else {
		b.WriteString("_t := _gopgext_trigger.Arg(_c)\n")
	}
	switch {
	case f.TriggerRow && f.HasError:
		b.WriteString("_r, _err := ")
	case f.TriggerRow:
		b.WriteString("_r := ")
	case f.HasError:
		b.WriteString("_err := ")
	}
	fmt.Fprintf(&b, "%s(_t)\n", f.GoName)
	if f.HasError {
		b.WriteString("if _err != nil {\n_c.Fail(_err)\nreturn\n}\n")
	}
	switch {
	case f.TriggerRow:
		b.WriteString("_gopgext_trigger.Return(_c, _t, _r)")
	case f.Trigger == "trigger":
		b.WriteString("_gopgext_trigger.ReturnDefault(_c, _t)")
	}
	return b.String()
}

// fieldStmt returns the statement that sets column i of _row from field f
// of _v.
func fieldStmt(i int, f Field) string {
	v := "_v." + f.GoName
	if f.Type.Custom != nil {
		v = conv(f.Type, v, true)
	}
	return fmt.Sprintf("_gopgext_fmgr.SetField%s%s[%s](_row, %d, %s)", kindSuffix[f.Type.Kind], of(f.Type), f.Type.Go, i, v)
}

// readStmt returns the statement that sets field f of _v from column i of
// the composite argument _r.
func readStmt(i int, f Field) string {
	t := f.Type
	var e string
	if t.Kind == Nullable {
		e = fmt.Sprintf("_gopgext_fmgr.FieldPtr[%s](_r, %d)", t.Go, i)
	} else {
		e = fmt.Sprintf("_gopgext_fmgr.Field%s%s[%s](_r, %d, %q)", kindSuffix[t.Kind], of(t), t.Go, i, f.SQLName)
	}
	if t.Custom != nil {
		e = conv(t, e, false)
	}
	return fmt.Sprintf("_v.%s = %s", f.GoName, e)
}

// genGo generates the Go wrappers gopgext_invoke calls (package main).
func genGo(pkg *Package) ([]byte, error) {
	var b bytes.Buffer
	if err := goTmpl.Execute(&b, pkg); err != nil {
		return nil, err
	}
	// The template keeps the output gofmt-clean; formatting it also catches
	// generated code that doesn't parse.
	src, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("generated Go wrappers: %v", err)
	}
	return src, nil
}

// genC generates the C functions PostgreSQL calls (V1 calling convention).
func genC(funcs []*Function) []byte {
	var b bytes.Buffer
	b.WriteString("/* Generated by gopgext: the SQL functions PostgreSQL calls. */\n#include \"gopgext.h\"\n")
	for _, f := range funcs {
		fmt.Fprintf(&b, `
/* %s */
void gopgext_go_%[2]s(struct gopgext_call *call);
PG_FUNCTION_INFO_V1(%[3]s);
Datum
%[3]s(PG_FUNCTION_ARGS)
{
	return gopgext_invoke(fcinfo, gopgext_go_%[2]s);
}
`, f.Signature(), f.GoName, f.Symbol)
	}
	return b.Bytes()
}

// Signature returns the SQL signature, e.g. "add(a integer, b integer)".
func (f *Function) Signature() string {
	var params []string
	for _, p := range f.Params {
		params = append(params, p.SQLName+" "+p.Type.SQL())
	}
	return f.SQLName + "(" + strings.Join(params, ", ") + ")"
}

func quoteIdent(s string) string { return `"` + strings.ReplaceAll(s, `"`, `""`) + `"` }

func quoteLiteral(s string) string { return "'" + strings.ReplaceAll(s, "'", "''") + "'" }

var sqlTmpl = template.Must(template.New("sql").Funcs(template.FuncMap{
	"ident":   quoteIdent,
	"literal": quoteLiteral,
	"base":    filepath.Base,
}).Parse(`-- Generated by gopgext from {{.ModPath}}.
\echo Use "CREATE EXTENSION {{.Name}}" to load this file. \quit
{{if .Types}}
-- Data types: shells, their functions, then the types.
{{range .Types}}CREATE TYPE {{ident .SQLName}};
{{end}}{{range .Funcs}}{{if .IOType}}{{template "func" .}}{{end}}{{end}}{{range .Types}}
-- {{.GoName}} ({{base .Pos.Filename}}:{{.Pos.Line}})
CREATE TYPE {{ident .SQLName}} (
	{{.CreateType}}
);
{{if .Doc}}COMMENT ON TYPE {{ident .SQLName}} IS {{literal .Doc}};
{{end}}{{end}}{{end}}{{range .Composites}}
-- {{.GoName}} ({{base .Pos.Filename}}:{{.Pos.Line}})
CREATE TYPE {{ident .SQLName}} AS (
	{{.Columns}}
);
{{if .Doc}}COMMENT ON TYPE {{ident .SQLName}} IS {{literal .Doc}};
{{end}}{{end}}{{range .Funcs}}{{if not (or .Manual .IOType)}}{{template "func" .}}{{end}}{{end -}}
{{define "func"}}
-- {{.GoName}} ({{base .Pos.Filename}}:{{.Pos.Line}})
CREATE FUNCTION {{ident .SQLName}}({{.SQLParams}})
RETURNS {{.Returns}}
AS 'MODULE_PATHNAME', '{{.Symbol}}'
{{.Attributes}};
{{if .Doc}}COMMENT ON FUNCTION {{ident .SQLName}}({{.ArgTypes}}) IS {{literal .Doc}};
{{end}}{{end}}`))

// SQLParams returns the parameters of CREATE FUNCTION, with OUT parameters
// for the columns of a row result.
func (f *Function) SQLParams() string {
	var params []string
	for _, p := range f.Params {
		params = append(params, quoteIdent(p.SQLName)+" "+p.Type.SQL())
	}
	if r := f.Result; r != nil && r.Struct != nil && r.Custom == nil && r.Kind != SetOf {
		for _, c := range r.Struct.Fields {
			params = append(params, "OUT "+quoteIdent(c.SQLName)+" "+c.Type.SQL())
		}
	}
	return strings.Join(params, ", ")
}

// Returns returns the RETURNS clause of CREATE FUNCTION.
func (f *Function) Returns() string {
	r := f.Result
	switch {
	case f.Trigger != "":
		return f.Trigger
	case r == nil:
		return "void"
	case r.Struct != nil && r.Custom == nil && r.Kind == SetOf:
		var cols []string
		for _, c := range r.Struct.Fields {
			cols = append(cols, quoteIdent(c.SQLName)+" "+c.Type.SQL())
		}
		return "TABLE (" + strings.Join(cols, ", ") + ")"
	case r.Struct != nil && r.Custom == nil:
		return "record"
	}
	return r.SQL()
}

// ArgTypes returns the SQL argument types, e.g. "integer, text[]".
func (f *Function) ArgTypes() string {
	var types []string
	for _, p := range f.Params {
		types = append(types, p.Type.SQL())
	}
	return strings.Join(types, ", ")
}

// Attributes returns the CREATE FUNCTION attributes, e.g.
// "LANGUAGE C IMMUTABLE STRICT PARALLEL SAFE".
func (f *Function) Attributes() string {
	attrs := []string{"LANGUAGE C", strings.ToUpper(f.Volatility)}
	if f.Strict {
		attrs = append(attrs, "STRICT")
	}
	if f.Leakproof {
		attrs = append(attrs, "LEAKPROOF")
	}
	if f.SecurityDefiner {
		attrs = append(attrs, "SECURITY DEFINER")
	}
	if f.Parallel != "" {
		attrs = append(attrs, "PARALLEL "+strings.ToUpper(f.Parallel))
	}
	if f.Cost != "" {
		attrs = append(attrs, "COST "+f.Cost)
	}
	if f.Rows != "" {
		attrs = append(attrs, "ROWS "+f.Rows)
	}
	return strings.Join(attrs, " ")
}

// genSQL generates the install script: CREATE FUNCTION for every function,
// then the frameworks' SQL and the project's sql/*.sql files.
func genSQL(name, modPath string, pkg *Package, frameworks [][]byte, sqlDir string) ([]byte, error) {
	var b bytes.Buffer
	err := sqlTmpl.Execute(&b, struct {
		Name, ModPath string
		Funcs         []*Function
		Types         []*SQLType // base types
		Composites    []*Struct
	}{name, modPath, pkg.Funcs, pkg.baseTypes(), pkg.composites()})
	if err != nil {
		return nil, err
	}
	for _, sql := range frameworks {
		b.Write(sql)
		if len(sql) > 0 && sql[len(sql)-1] != '\n' {
			b.WriteByte('\n')
		}
	}
	files, err := filepath.Glob(filepath.Join(sqlDir, "*.sql"))
	if err != nil {
		return nil, err
	}
	sort.Strings(files)
	for _, p := range files {
		data, err := os.ReadFile(p)
		if err != nil {
			return nil, err
		}
		fmt.Fprintf(&b, "\n-- %s/%s\n", SQLDir, filepath.Base(p))
		b.Write(data)
		if len(data) > 0 && data[len(data)-1] != '\n' {
			b.WriteByte('\n')
		}
	}
	return b.Bytes(), nil
}

// genExports generates the linker version script: the library exports only
// what PostgreSQL looks up.
func genExports(funcs []*Function, cFuncs []string) []byte {
	var b bytes.Buffer
	b.WriteString("/* Generated by gopgext: the library exports only what PostgreSQL looks up. */\n{\n\tglobal:\n")
	b.WriteString("\t\tPg_magic_func;\n\t\t_PG_init;\n\t\tpg_finfo_gopgext_fn_*;\n\t\tgopgext_fn_*;\n")
	for _, f := range funcs {
		if !strings.HasPrefix(f.Symbol, "gopgext_fn_") {
			fmt.Fprintf(&b, "\t\t%s;\n\t\tpg_finfo_%s;\n", f.Symbol, f.Symbol)
		}
	}
	for _, f := range cFuncs {
		fmt.Fprintf(&b, "\t\t%s;\n\t\tpg_finfo_%s;\n", f, f)
	}
	b.WriteString("\tlocal: *;\n};\n")
	return b.Bytes()
}

// genControl generates the extension's control file; requires are the
// extensions it depends on.
func genControl(name, version, comment string, trusted bool, requires []string) []byte {
	var b bytes.Buffer
	fmt.Fprintf(&b, "# %s extension (generated by gopgext)\n", name)
	fmt.Fprintf(&b, "comment = %s\n", quoteLiteral(comment))
	fmt.Fprintf(&b, "default_version = %s\n", quoteLiteral(version))
	fmt.Fprintf(&b, "module_pathname = %s\n", quoteLiteral("$libdir/"+name))
	b.WriteString("relocatable = true\n")
	if trusted {
		b.WriteString("trusted = true\n")
	}
	if len(requires) > 0 {
		fmt.Fprintf(&b, "requires = %s\n", quoteLiteral(strings.Join(requires, ", ")))
	}
	return b.Bytes()
}

func (pkg *Package) baseTypes() []*SQLType {
	var ts []*SQLType
	for _, t := range pkg.Types {
		if !t.Composite {
			ts = append(ts, t)
		}
	}
	return ts
}

// composites returns the composite types, in declaration order.
func (pkg *Package) composites() []*Struct {
	var cs []*Struct
	for _, t := range pkg.Types {
		for _, st := range pkg.Structs {
			if st.Composite == t {
				cs = append(cs, st)
			}
		}
	}
	return cs
}

// SQLName, Doc and Columns describe a composite type.
func (st *Struct) SQLName() string { return st.Composite.SQLName }
func (st *Struct) Doc() string     { return st.Composite.Doc }

func (st *Struct) Columns() string {
	var cols []string
	for _, c := range st.Fields {
		cols = append(cols, quoteIdent(c.SQLName)+" "+c.Type.SQL())
	}
	return strings.Join(cols, ",\n\t")
}

// UsesTrigger reports whether generated code uses gopgext/trigger.
func (pkg *Package) UsesTrigger() bool {
	for _, f := range pkg.Funcs {
		if f.Trigger != "" {
			return true
		}
	}
	return false
}

// UsesAgg reports whether generated code uses gopgext/agg.
func (pkg *Package) UsesAgg() bool {
	for _, f := range pkg.Funcs {
		if f.Result != nil && f.Result.Go == aggState {
			return true
		}
		for _, p := range f.Params {
			if p.Type.Go == aggState {
				return true
			}
		}
	}
	return false
}
