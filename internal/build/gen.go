// genGo generates the Go wrappers gopgext_invoke calls (package main).
func genGo(funcs []*Function) []byte {
	var b bytes.Buffer
	b.WriteString(`// Code generated by gopgext. DO NOT EDIT.

package main

import _gopgext_fmgr "gopgext/fmgr"

// Package initialization and main run when the library is loaded (_PG_init).
//
//export gopgext_go_init
func _gopgext_go_init(c *_gopgext_fmgr.Call) {
	defer c.End(c.Begin(false))
	_gopgext_fmgr.Init(c)
}
`)
	for _, f := range funcs {
		fmt.Fprintf(&b, "\n// %s: %s\n//\n//export gopgext_go_%s\nfunc _gopgext_go_%s(_c *_gopgext_fmgr.Call) {\n",
			f.GoName, f.Signature(), f.GoName, f.GoName)
		fmt.Fprintf(&b, "\tdefer _c.End(_c.Begin(%v))\n", f.ReadOnly())
		var args []string
		for i, p := range f.Params {
			var a string
			switch p.Type.Kind {
			case Scalar:
				a = fmt.Sprintf("_gopgext_fmgr.Arg[%s](_c, %d, %q)", p.Type.Go, i, p.SQLName)
			case Nullable:
				a = fmt.Sprintf("_gopgext_fmgr.ArgPtr[%s](_c, %d)", p.Type.Go, i)
			case Array:
				a = fmt.Sprintf("_gopgext_fmgr.ArgArray[%s](_c, %d, %q)", p.Type.Go, i, p.SQLName)
			case NullableArray:
				a = fmt.Sprintf("_gopgext_fmgr.ArgArrayPtr[%s](_c, %d, %q)", p.Type.Go, i, p.SQLName)
			case NullableElems:
				a = fmt.Sprintf("_gopgext_fmgr.ArgArrayNullable[%s](_c, %d, %q)", p.Type.Go, i, p.SQLName)
			}
			args = append(args, a)
		}
		call := fmt.Sprintf("%s(%s)", f.GoName, strings.Join(args, ", "))
		var lhs []string
		if f.Result != nil {
			lhs = append(lhs, "_r")
		}
		if f.HasError {
			lhs = append(lhs, "_err")
		}
		if len(lhs) > 0 {
			fmt.Fprintf(&b, "\t%s := %s\n", strings.Join(lhs, ", "), call)
		} else {
			fmt.Fprintf(&b, "\t%s\n", call)
		}
		if f.HasError {
			b.WriteString("\tif _err != nil {\n\t\t_c.Fail(_err)\n\t\treturn\n\t}\n")
		}
		if f.Result != nil {
			switch f.Result.Kind {
			case Scalar:
				b.WriteString("\t_gopgext_fmgr.Return(_c, _r)\n")
			case Nullable:
				b.WriteString("\t_gopgext_fmgr.ReturnPtr(_c, _r)\n")
			case Array:
				b.WriteString("\t_gopgext_fmgr.ReturnArray(_c, _r)\n")
			case NullableArray:
				b.WriteString("\t_gopgext_fmgr.ReturnArrayPtr(_c, _r)\n")
			case NullableElems:
				b.WriteString("\t_gopgext_fmgr.ReturnArrayNullable(_c, _r)\n")
			case SetOf:
				b.WriteString("\t_gopgext_fmgr.ReturnSet(_c, _r)\n")
			}
		}
		b.WriteString("}\n")
	}
	return b.Bytes()
}

// genC generates the C functions PostgreSQL calls (V1 calling convention).
func genC(funcs []*Function) []byte {
	var b bytes.Buffer
	b.WriteString("/* Generated by gopgext: the SQL functions PostgreSQL calls. */\n#include \"gopgext.h\"\n")
	for _, f := range funcs {
		fmt.Fprintf(&b, `
/* %s */
void gopgext_go_%[2]s(struct gopgext_call *call);
PG_FUNCTION_INFO_V1(%[3]s);
Datum
%[3]s(PG_FUNCTION_ARGS)
{
	return gopgext_invoke(fcinfo, gopgext_go_%[2]s);
}
`, f.Signature(), f.GoName, f.Symbol)
	}
	return b.Bytes()
}

// Signature returns the SQL signature, e.g. "add(a integer, b integer)".
func (f *Function) Signature() string {
	var params []string
	for _, p := range f.Params {
		params = append(params, p.SQLName+" "+p.Type.SQL())
	}
	return f.SQLName + "(" + strings.Join(params, ", ") + ")"
}

func quoteIdent(s string) string { return `"` + strings.ReplaceAll(s, `"`, `""`) + `"` }

func quoteLiteral(s string) string { return "'" + strings.ReplaceAll(s, "'", "''") + "'" }

// genSQL generates the install script: CREATE FUNCTION for every function,
// then the project's sql/*.sql files.
func genSQL(name, modPath string, funcs []*Function, frameworks [][]byte, sqlDir string) ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintf(&b, "-- Generated by gopgext from %s.\n", modPath)
	fmt.Fprintf(&b, "\\echo Use \"CREATE EXTENSION %s\" to load this file. \\quit\n", name)
	for _, f := range funcs {
		if f.Manual {
			continue
		}
		var params, types []string
		for _, p := range f.Params {
			params = append(params, quoteIdent(p.SQLName)+" "+p.Type.SQL())
			types = append(types, p.Type.SQL())
		}
		ret := "void"
		if f.Result != nil {
			ret = f.Result.SQL()
		}
		attrs := []string{"LANGUAGE C", strings.ToUpper(f.Volatility)}
		if f.Strict {
			attrs = append(attrs, "STRICT")
		}
		if f.Leakproof {
			attrs = append(attrs, "LEAKPROOF")
		}
		if f.SecurityDefiner {
			attrs = append(attrs, "SECURITY DEFINER")
		}
		if f.Parallel != "" {
			attrs = append(attrs, "PARALLEL "+strings.ToUpper(f.Parallel))
		}
		if f.Cost != "" {
			attrs = append(attrs, "COST "+f.Cost)
		}
		if f.Rows != "" {
			attrs = append(attrs, "ROWS "+f.Rows)
		}
		fmt.Fprintf(&b, "\n-- %s (%s:%d)\nCREATE FUNCTION %s(%s)\nRETURNS %s\nAS 'MODULE_PATHNAME', '%s'\n%s;\n",
			f.GoName, filepath.Base(f.Pos.Filename), f.Pos.Line,
			quoteIdent(f.SQLName), strings.Join(params, ", "), ret, f.Symbol, strings.Join(attrs, " "))
		if f.Doc != "" {
			fmt.Fprintf(&b, "COMMENT ON FUNCTION %s(%s) IS %s;\n",
				quoteIdent(f.SQLName), strings.Join(types, ", "), quoteLiteral(f.Doc))
		}
	}
	for _, sql := range frameworks {
		b.Write(sql)
		if len(sql) > 0 && sql[len(sql)-1] != '\n' {
			b.WriteByte('\n')
		}
	}
	files, err := filepath.Glob(filepath.Join(sqlDir, "*.sql"))
	if err != nil {
		return nil, err
	}
	sort.Strings(files)
	for _, p := range files {
		data, err := os.ReadFile(p)
		if err != nil {
			return nil, err
		}
		fmt.Fprintf(&b, "\n-- %s/%s\n", SQLDir, filepath.Base(p))
		b.Write(data)
		if len(data) > 0 && data[len(data)-1] != '\n' {
			b.WriteByte('\n')
		}
	}
	return b.Bytes(), nil
}

// genExports generates the linker version script: the library exports only
// what PostgreSQL looks up.
func genExports(funcs []*Function, cFuncs []string) []byte {
	var b bytes.Buffer
	b.WriteString("/* Generated by gopgext: the library exports only what PostgreSQL looks up. */\n{\n\tglobal:\n")
	b.WriteString("\t\tPg_magic_func;\n\t\t_PG_init;\n\t\tpg_finfo_gopgext_fn_*;\n\t\tgopgext_fn_*;\n")
	for _, f := range funcs {
		if !strings.HasPrefix(f.Symbol, "gopgext_fn_") {
			fmt.Fprintf(&b, "\t\t%s;\n\t\tpg_finfo_%s;\n", f.Symbol, f.Symbol)
		}
	}
	for _, f := range cFuncs {
		fmt.Fprintf(&b, "\t\t%s;\n\t\tpg_finfo_%s;\n", f, f)
	}
	b.WriteString("\tlocal: *;\n};\n")
	return b.Bytes()
}

// genControl generates the extension's control file.
func genControl(name, version, comment string, trusted bool) []byte {
	var b bytes.Buffer
	fmt.Fprintf(&b, "# %s extension (generated by gopgext)\n", name)
	fmt.Fprintf(&b, "comment = %s\n", quoteLiteral(comment))
	fmt.Fprintf(&b, "default_version = %s\n", quoteLiteral(version))
	fmt.Fprintf(&b, "module_pathname = %s\n", quoteLiteral("$libdir/"+name))
	b.WriteString("relocatable = true\n")
	if trusted {
		b.WriteString("trusted = true\n")
	}
	return b.Bytes()
}
