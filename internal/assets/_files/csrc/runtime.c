/*
 * CHECK_FOR_INTERRUPTS() for Go: processes pending interrupts. Benign ones
 * (barriers, stats, ...) are handled and NULL is returned; a query cancel or
 * timeout error is caught, becomes the pending error (re-thrown when the call
 * returns) and is returned. Termination requests end the backend.
 */
ErrorData *
gopgext_check_interrupts(void)
{
	if (!INTERRUPTS_PENDING_CONDITION())
		return NULL;
	GOPGEXT_GUARD(ProcessInterrupts());
}

/*
 * Garbage collector support (TinyGo's asm_amd64.S, which isn't part of the
 * object TinyGo emits): push the callee-saved registers so the conservative
 * scan finds pointers held in them, then scan from the stack pointer up.
 * tinygo_longjmp resumes at a deferred call's landing pad after a panic:
 * the frame holds {jumpSP, jumpPC, frame pointer}. TinyGo keeps frame
 * pointers on linux/amd64 and saves rbp in the defer frame
 * (tinygo-org/tinygo 4a47cfde), so restore it, or a function that recovers
 * a panic keeps running with the wrong frame pointer. TinyGo before 0.45
 * lists rbp as clobbered by setjmp, so restoring it is harmless there.
 */
asm(".pushsection .text.tinygo_scanCurrentStack,\"ax\",@progbits\n"
	".globl tinygo_scanCurrentStack\n"
	".hidden tinygo_scanCurrentStack\n"
	".type tinygo_scanCurrentStack,@function\n"
	"tinygo_scanCurrentStack:\n"
	"\tpushq %rbx\n"
	"\tpushq %rbp\n"
	"\tpushq %r12\n"
	"\tpushq %r13\n"
	"\tpushq %r14\n"
	"\tpushq %r15\n"
	"\tsubq $8, %rsp\n"
	"\tmovq %rsp, %rdi\n"
	"\tcallq tinygo_scanstack@PLT\n"
	"\taddq $56, %rsp\n"
	"\tretq\n"
	".size tinygo_scanCurrentStack, .-tinygo_scanCurrentStack\n"
	".popsection\n"
	".pushsection .text.tinygo_longjmp,\"ax\",@progbits\n"
	".globl tinygo_longjmp\n"
	".hidden tinygo_longjmp\n"
	".type tinygo_longjmp,@function\n"
	"tinygo_longjmp:\n"
	"\tmovq 0(%rdi), %rsp\n"
	"\tmovq 16(%rdi), %rbp\n"
	"\tmovq 8(%rdi), %rax\n"
	"\tjmpq *%rax\n"
	".size tinygo_longjmp, .-tinygo_longjmp\n"
	".popsection\n");

